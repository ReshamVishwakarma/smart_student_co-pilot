from datetime import datetime
from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class TaskItem(BaseModel):
    """Student academic task or exam record."""

    id: str = Field(..., description="Unique task identifier")
    title: str = Field(..., description="Task title / description")
    course: str = Field(..., description="Course code or subject")
    deadline: datetime = Field(..., description="ISO 8601 task deadline timestamp")
    is_completed: bool = Field(default=False, description="Completion status flag")
    estimated_minutes: int = Field(default=60, description="Estimated effort in minutes")
    tags: List[str] = Field(default_factory=list, description="Categorization tags")


class DeadlineRuleConfig(BaseModel):
    """Configuration thresholds for the deterministic proactive deadline rule."""

    urgent_window_hours: float = Field(
        default=12.0,
        description="Hours before deadline where a task is considered urgently critical",
    )
    upcoming_window_hours: float = Field(
        default=48.0,
        description="Hours before deadline where a task triggers advance preparation nudges",
    )


class SuggestionExplanation(BaseModel):
    """Explainability metadata answering 'Why am I seeing this?'."""

    trigger: str = Field(..., description="The contextual signal or rule condition that triggered this suggestion")
    interruption_cost: str = Field(..., description="Focus / interruption gate score rationale")
    rationale: str = Field(..., description="Pedagogical or academic justification for this action")


class ProactiveSuggestionItem(BaseModel):
    """Generated proactive recommendation surfaced to the student."""

    id: str = Field(..., description="Unique suggestion identifier")
    task_id: str = Field(..., description="Referenced task ID that prompted the suggestion")
    title: str = Field(..., description="Brief actionable suggestion header")
    description: str = Field(..., description="Detailed advice or instructions")
    category: str = Field(default="academic_deadline", description="Suggestion category")
    priority: Literal["low", "medium", "high", "urgent"] = Field(
        default="medium", description="Priority level"
    )
    confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Deterministic rule confidence score (0.0 to 1.0)"
    )
    is_simulated: bool = Field(
        default=False,
        description="False when generated by genuine Python rule engine; True when mock stub",
    )
    explanation: SuggestionExplanation
    created_at: str
    status: Literal["pending", "accepted", "dismissed", "snoozed"] = Field(
        default="pending", description="Student feedback lifecycle status"
    )


class EvaluateTasksRequest(BaseModel):
    """Request payload for custom task evaluation."""

    tasks: List[TaskItem]
    config: Optional[DeadlineRuleConfig] = None
    reference_time: Optional[datetime] = None
